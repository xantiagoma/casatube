/**
 * Plugins: what is installed, what it declares, whether it is on, what it needs
 * configured — and, since the editor, its source.
 *
 * The manifest is readable before any of the plugin's code runs, which is what
 * lets this list say what a plugin *would* do rather than only what it is
 * called. Broken plugins are listed too — a plugin that failed to load is the
 * one you most need to see.
 *
 * ## Two rules this folder holds up
 *
 * 🔴 **A file is opened by filename, never by plugin name.** A file with a
 * syntax error has no manifest and therefore no name; the runtime invents one
 * from the filename so it can be listed at all. Keying the editor on the
 * manifest would make the one file that needs fixing the one file that cannot
 * be opened.
 *
 * ⚠️ **A secret's value never arrives.** `GET /api/plugins/:name/settings`
 * answers with `configured` and `source` for anything marked `secret`, and no
 * value — the same rule the cookies file follows (PLAN §12). So a field for a
 * secret starts empty even when one is set, and `null` is how the UI says
 * "clear it and use whatever is underneath".
 */
import { useMutation, useQuery, useQueryClient, type UseQueryResult } from "@tanstack/react-query";

import type { PluginStatus } from "../../core/plugin-runtime";
import type { ResolvedSetting } from "../../core/plugin-settings";
import { api, unwrap } from "./client";
import { keys } from "./keys";

export interface PluginListing {
  plugins: PluginStatus[];
  /** Where a plugin file goes on this server — the answer an empty list needs. */
  dir: string;
}

export interface PluginSaved extends PluginListing {
  /** How the runtime sees the file that was just written. `state: "error"` is a normal outcome. */
  saved: PluginStatus | null;
  /** ⚠️ Generated by the server on **every** save. Render it; do not summarise it. */
  warning: string;
}

/**
 * The starter plugin, as a file.
 *
 * A plain URL rather than an Eden call because the browser is doing the
 * fetching: this is the `href` of a download link, and the server sends it with
 * `Content-Disposition`, so it lands already named. Same shape as
 * `libraryFileUrl` in `library.ts`, and here for the same reason — the folder
 * that knows the API is this one (R3).
 */
export const PLUGIN_TEMPLATE_URL = "/api/plugins/template";

export function usePlugins(): UseQueryResult<PluginListing, Error> {
  return useQuery({
    queryKey: keys.plugins,
    queryFn: async () => unwrap(await api.api.plugins.get()),
    retry: 0,
  });
}

export interface PluginDocs {
  markdown: string;
  filename: string;
  dir: string;
}

/**
 * The documentation, served by the API rather than linked to a file.
 *
 * ⚠️ It cannot be a link to `plugins/README.md`: the repository is not in the
 * image, so that link 404s exactly where someone is most likely to click it.
 * The server holds a condensed copy and hands it over — see
 * `api/plugin-template.ts`.
 *
 * Fetched only when the dialog opens: it is a few kilobytes nobody needs on the
 * way past.
 */
export function usePluginDocs(enabled: boolean): UseQueryResult<PluginDocs, Error> {
  return useQuery({
    queryKey: keys.pluginDocs,
    queryFn: async () => unwrap(await api.api.plugins.docs.get()),
    enabled,
    // It changes when the server is upgraded, and not otherwise.
    staleTime: Number.POSITIVE_INFINITY,
    retry: 0,
  });
}

/** ⚠️ Enabling runs the plugin's `setup()` for the first time, so it can fail. */
export function useTogglePlugin() {
  const client = useQueryClient();
  return useMutation<PluginStatus, Error, { name: string; enabled: boolean }>({
    mutationFn: async ({ name, enabled }) =>
      unwrap(enabled ? await api.api.plugins({ name }).enable.post() : await api.api.plugins({ name }).disable.post()),
    onSuccess: () => void client.invalidateQueries({ queryKey: keys.plugins }),
  });
}

export interface PluginSource {
  file: string;
  source: string;
}

/** One plugin file's text. `null` closes the query rather than fetching a file called "null". */
export function usePluginSource(file: string | null): UseQueryResult<PluginSource, Error> {
  return useQuery({
    queryKey: keys.pluginSource(file ?? ""),
    queryFn: async () => unwrap(await api.api.plugins.source.get({ query: { file: file ?? "" } })),
    enabled: file !== null && file !== "",
    // The file on the server changes only through this screen, and every write
    // updates this entry directly. Refetching on a window focus would discard
    // whatever is half-typed in the editor.
    staleTime: Number.POSITIVE_INFINITY,
    retry: 0,
  });
}

/**
 * The annotated starter, as text to prefill a new file with.
 *
 * The same bytes the download button hands over — one source of the starting
 * point, two ways to receive it. It is served as `text/plain`, so what comes
 * back is the string itself.
 */
export function usePluginTemplate(enabled: boolean): UseQueryResult<string, Error> {
  return useQuery({
    queryKey: keys.pluginTemplate,
    queryFn: async () => unwrap(await api.api.plugins.template.get()),
    enabled,
    staleTime: Number.POSITIVE_INFINITY,
    retry: 0,
  });
}

export interface SavePluginSource {
  file: string;
  source: string;
  /** Required for a file that already exists — the server answers 409 otherwise. */
  overwrite?: boolean;
}

/**
 * Write a plugin file and reload the runtime.
 *
 * ⚠️ Success here does **not** mean the plugin loaded. A file that does not
 * compile is written, reloaded, and comes back as `saved.state === "error"`
 * with the reason attached — which is the answer the editor has to show.
 * Treating that as a failed request would be wrong twice over: the write did
 * happen, and nothing else on the server was affected by it.
 */
export function useSavePluginSource() {
  const client = useQueryClient();
  return useMutation<PluginSaved, Error, SavePluginSource>({
    mutationFn: async ({ file, source, overwrite }) =>
      unwrap(await api.api.plugins.source.put({ file, source, ...(overwrite === true ? { overwrite } : {}) })),
    onSuccess: (result, variables) => {
      client.setQueryData(keys.plugins, { plugins: result.plugins, dir: result.dir });
      client.setQueryData(keys.pluginSource(variables.file), { file: variables.file, source: variables.source });
      // A save reloads every plugin, so every resolved value could have moved.
      // Dropping them all is cheaper than working out which.
      void client.invalidateQueries({ queryKey: ["plugins", "settings"] });
    },
  });
}

export function useDeletePluginSource() {
  const client = useQueryClient();
  return useMutation<PluginListing, Error, string>({
    mutationFn: async (file) => unwrap(await api.api.plugins.source.delete(undefined, { query: { file } })),
    onSuccess: (result, file) => {
      client.setQueryData(keys.plugins, result);
      client.removeQueries({ queryKey: keys.pluginSource(file) });
    },
  });
}

export interface PluginSettingsView {
  name: string;
  settings: ResolvedSetting[];
}

export function usePluginSettings(name: string | null): UseQueryResult<PluginSettingsView, Error> {
  return useQuery({
    queryKey: keys.pluginSettings(name ?? ""),
    queryFn: async () => unwrap(await api.api.plugins({ name: name ?? "" }).settings.get()),
    enabled: name !== null && name !== "",
    retry: 0,
  });
}

/**
 * Store values and put them into effect.
 *
 * `null` clears a key. That is the revert button, and it is why the body is a
 * patch rather than the whole record: "leave this one as it is" and "put this
 * one back to the environment value" have to be different requests, and against
 * a full record they would look identical.
 */
export function useSavePluginSettings() {
  const client = useQueryClient();
  return useMutation<PluginSettingsView, Error, { name: string; values: Record<string, string | null> }>({
    mutationFn: async ({ name, values }) => unwrap(await api.api.plugins({ name }).settings.put({ values })),
    onSuccess: (result) => {
      client.setQueryData(keys.pluginSettings(result.name), result);
      // Saving reloads the runtime: state, logs and `missingSettings` all move.
      void client.invalidateQueries({ queryKey: keys.plugins });
    },
  });
}

// --- Which plugins would act on a URL ---------------------------------------

export interface ApplicableListing {
  url: string;
  /** Everything whose `matches` claims this URL — **switched on or not**. */
  plugins: PluginStatus[];
}

/**
 * `GET /api/plugins/applicable?url=` — the answer PLAN §5 wrote this route for
 * and nothing has asked for until now.
 *
 * 🔴 **Asking costs nothing and runs nothing.** `matches` is static metadata,
 * so the server answers out of manifests it already holds: no `setup()`, no
 * hook, no network, no plugin code of any kind. That is what makes it safe to
 * fire the moment a URL is analyzed rather than making it a button.
 *
 * ⚠️ **A plugin in this list is not necessarily running.** `applicableTo`
 * returns everything that *claims* the URL and leaves out only the broken ones,
 * so the list mixes active and disabled plugins and the screen has to say which
 * is which. Reading it as "these will run" is the one wrong reading.
 *
 * `null` closes the query — nothing is asked before there is a URL to ask about.
 */
export function useApplicablePlugins(url: string | null): UseQueryResult<ApplicableListing, Error> {
  const trimmed = url?.trim() ?? "";
  return useQuery({
    queryKey: keys.pluginsApplicable(trimmed),
    queryFn: async () => unwrap(await api.api.plugins.applicable.get({ query: { url: trimmed } })),
    enabled: trimmed !== "",
    // Manifests change when a file is saved, and every save already invalidates
    // the `plugins` prefix this key sits under.
    staleTime: 60_000,
    retry: 0,
  });
}
