/**
 * `/api/plugins` — what is installed, what it asks for, what it would do, and
 * (since the editor) how to write it.
 *
 * The oldest endpoint here is `GET /api/plugins/applicable?url=`. PLAN section 5
 * says a plugin is not a black box that quietly runs on everything: it declares
 * `matches`, that declaration is readable **before any of its code runs**, and
 * so the download window can paste a URL, show which plugins would act on it,
 * what each one would do, and leave the choice to the user.
 *
 * ## Two things were added, and both change what this file has to be careful about
 *
 * **A file editor.** `GET/PUT/DELETE /api/plugins/source` create, replace and
 * remove a file in the plugins directory, and every write **reloads the
 * runtime** — no restart, and a broken save comes back as an `error` row in the
 * same response rather than as a server that will not boot. Files are addressed
 * by **filename, not plugin name**: a file that does not parse has no manifest,
 * so it has no name, and it is exactly the file someone needs to open.
 *
 * ⚠️ Writing a file here is executing code on the server. The response carries
 * `warning` — generated by `saveWarning()`, on every save — because an editor
 * makes that easier, which makes the warning matter more rather than less.
 *
 * **A settings form.** A plugin declares what it needs configured and this
 * answers with the values resolved through every layer. 🔴 `redact()` and
 * `redactDeclarations()` are applied to **everything** that leaves this module:
 * a setting marked `secret` never has its value on the wire — not in the list,
 * not in the settings endpoint, not as a manifest default — the same rule the
 * cookies file follows (PLAN section 12).
 *
 * The routes take the runtime and the directory directly instead of
 * `AppContext`. A plugin registry is not a database or a queue, and passing it
 * explicitly is what lets a test stand these endpoints up over a temporary
 * directory with no SQLite file anywhere near it.
 */
import { Elysia, status, t } from "elysia";
import { Result } from "better-result";

import { NotFound } from "../core/errors";
import { deletePluginFile, pluginFileExists, readPluginFile, writePluginFile } from "../core/plugin-files";
import type { PluginRuntime, PluginStatus } from "../core/plugin-runtime";
import { redact, redactDeclarations, type ResolvedSetting } from "../core/plugin-settings";
import { fail } from "./errors";
import { PLUGIN_TEMPLATE_FILENAME, pluginDocs, pluginTemplate, saveWarning } from "./plugin-template";

/**
 * A plugin as the browser sees it.
 *
 * The manifest, the state, and the *shape* of its configuration — never a
 * configured value. `settings` here is the declaration, which is what lets the
 * screen draw a form; the values come from `/settings`, redacted.
 */
export interface PluginView extends PluginStatus {}

export interface PluginListing {
  plugins: PluginView[];
  /**
   * The absolute directory a plugin file goes in.
   *
   * 🔴 Part of the listing rather than something the browser guesses, because
   * an empty list is exactly when it is needed: "No plugins installed" with no
   * path is a dead end, and the path depends on `DATA_DIR`, which only the
   * server knows.
   */
  dir: string;
}

export interface ApplicableListing {
  url: string;
  /** Every plugin that would act on this URL, enabled or not. */
  plugins: PluginView[];
}

export interface PluginSource {
  file: string;
  source: string;
}

export interface PluginSaved extends PluginListing {
  /** The file that was written, as the runtime sees it now — `error` state included. */
  saved: PluginView | null;
  /** ⚠️ On every save. See the header. */
  warning: string;
}

export interface PluginSettingsView {
  name: string;
  /** Secrets carry `configured` and `source`, never a value. */
  settings: ResolvedSetting[];
}

/**
 * The one place a `PluginStatus` becomes something a browser may see.
 *
 * Everything that answers with a plugin goes through here, so "a secret never
 * leaves the server" is a property of this module rather than a habit each
 * handler has to remember.
 */
function view(plugin: PluginStatus): PluginView {
  const declared = redactDeclarations(plugin.settings);
  const { settings, ...rest } = plugin;
  void settings;
  return { ...rest, ...(declared ? { settings: declared } : {}) };
}

/** 400 for a name this directory would never load, 409 for one that is taken. */
function refuse(code: 400 | 409, tag: string, message: string) {
  return status(code, { tag, message, retryable: false });
}

/**
 * @param runtime The loaded plugins. Writes reload it in place.
 * @param dir The plugins directory: where files are written, and the answer a
 * screen with no plugins on it needs before it can say anything useful.
 */
export function pluginRoutes(runtime: PluginRuntime, dir = "") {
  const listing = (): PluginListing => ({ plugins: runtime.list().map(view), dir });
  const placeholder = dir === "" ? "DATA_DIR/plugins" : dir;

  /** After every write. One reload, then one listing computed from the result. */
  async function reloadInto(file: string): Promise<PluginSaved> {
    await runtime.load();
    const plugins = runtime.list().map(view);
    const saved = plugins.find((plugin) => plugin.file === file) ?? null;
    return { plugins, dir, saved, warning: saveWarning(saved?.needs ?? []) };
  }

  return (
    new Elysia({ prefix: "/plugins" })
      /** Everything found, broken ones included — a plugin that failed to load is the one you most need to see. */
      .get("/", (): PluginListing => listing())

      /**
       * A starter plugin, as a file to save.
       *
       * 🔴 Still a download, even now that the editor exists: the editor asks
       * for this same text to prefill a new file, and a browser that wants the
       * file on disk instead gets it named by `Content-Disposition`. One source
       * of the starting point, two ways to receive it.
       *
       * `text/plain` on purpose — a browser must never be tempted to do
       * anything with this but save it.
       */
      .get(
        "/template",
        () =>
          new Response(pluginTemplate(placeholder), {
            headers: {
              "content-type": "text/plain; charset=utf-8",
              "content-disposition": `attachment; filename="${PLUGIN_TEMPLATE_FILENAME}"`,
            },
          }),
      )

      /**
       * The documentation, served rather than linked.
       *
       * A link to a file in the repository is a link a running server cannot
       * honour — the image has no repository in it. See `plugin-template.ts`.
       */
      .get("/docs", () => ({
        markdown: pluginDocs(placeholder),
        filename: PLUGIN_TEMPLATE_FILENAME,
        dir,
      }))

      /**
       * Which plugins would act on this URL.
       *
       * Answered entirely from static manifests, so asking costs nothing and
       * runs none of the plugins. Broken plugins are excluded: they cannot act
       * on anything, and offering the user a toggle for one would be a lie.
       */
      .get(
        "/applicable",
        ({ query }): ApplicableListing => ({
          url: query.url,
          plugins: runtime.applicableTo(query.url).map(view),
        }),
        { query: t.Object({ url: t.String({ minLength: 1 }) }) },
      )

      /**
       * One plugin file's source, for the editor to open.
       *
       * By filename, and a file with no loadable plugin in it answers here just
       * the same — see the header.
       */
      .get(
        "/source",
        async ({ query }) => {
          const read = await readPluginFile(dir, query.file);
          if (Result.isError(read)) {
            // Told apart on purpose: a name this directory could never load is
            // a bad request, and a name that is fine but absent is a 404. One
            // status for both would make "you typed it wrong" and "it is gone"
            // the same message.
            return read.error.startsWith("there is no plugin file")
              ? fail(new NotFound({ what: "plugin file", id: query.file }))
              : refuse(400, "InvalidPluginFile", read.error);
          }
          return { file: query.file, source: read.value } satisfies PluginSource;
        },
        { query: t.Object({ file: t.String({ minLength: 1 }) }) },
      )

      /**
       * Create or replace a plugin file, then reload.
       *
       * 🔴 `overwrite` defaults to **false**, so saving a new plugin cannot
       * silently land on top of one that is already there. The editor sends
       * `true` only for a file it opened.
       *
       * ⚠️ A file that does not compile is a completely normal outcome of this
       * route and answers **200**: the runtime records the failure against that
       * one plugin and everything else stays loaded, which is exactly the
       * behaviour that has to survive an editor existing. `saved.state` is
       * `"error"` and `saved.error` carries the message — the browser shows it,
       * and nothing about the server changed.
       */
      .put(
        "/source",
        async ({ body }) => {
          const exists = await pluginFileExists(dir, body.file);
          if (exists && body.overwrite !== true) {
            return refuse(409, "PluginFileExists", `there is already a plugin file called "${body.file}"`);
          }
          const written = await writePluginFile(dir, body.file, body.source);
          if (Result.isError(written)) return refuse(400, "InvalidPluginFile", written.error);
          return await reloadInto(written.value);
        },
        {
          body: t.Object({
            file: t.String({ minLength: 1 }),
            source: t.String(),
            overwrite: t.Optional(t.Boolean()),
          }),
        },
      )

      /**
       * Remove a plugin file, then reload.
       *
       * The file is unlinked rather than moved aside. A plugin is source code —
       * the copy that matters is wherever its author keeps it — and a hidden
       * second copy in the data directory is a credential in a file nobody
       * remembers.
       */
      .delete(
        "/source",
        async ({ query }) => {
          const removed = await deletePluginFile(dir, query.file);
          if (Result.isError(removed)) {
            return removed.error.startsWith("there is no plugin file")
              ? fail(new NotFound({ what: "plugin file", id: query.file }))
              : refuse(400, "InvalidPluginFile", removed.error);
          }
          await runtime.load();
          return listing();
        },
        { query: t.Object({ file: t.String({ minLength: 1 }) }) },
      )

      /**
       * Turn one on. This is what runs its `setup()` for the first time, which
       * is why it can fail: a plugin whose setup throws reports it here rather
       * than at a boot nobody was watching.
       */
      .post(
        "/:name/enable",
        async ({ params }) => toggle(await runtime.enable(params.name), params.name),
        { params: t.Object({ name: t.String() }) },
      )

      /** Turn one off. Its hooks stop being dispatched and its providers stop claiming URLs. */
      .post(
        "/:name/disable",
        async ({ params }) => toggle(await runtime.disable(params.name), params.name),
        { params: t.Object({ name: t.String() }) },
      )

      /** What this plugin needs, and what each value currently resolves to. Secrets redacted. */
      .get(
        "/:name/settings",
        ({ params }) => {
          const found = runtime.settings(params.name);
          if (Result.isError(found)) return fail(new NotFound({ what: "plugin", id: params.name }));
          return { name: params.name, settings: redact(found.value) } satisfies PluginSettingsView;
        },
        { params: t.Object({ name: t.String() }) },
      )

      /**
       * Store values, and put them into effect.
       *
       * A key set to `null` is **cleared**, which is the whole of the "use the
       * environment value again" button: the stored layer is removed and the
       * one underneath — the variable, untouched, or the manifest's default —
       * answers again. Nothing here ever writes to the environment.
       *
       * 🔴 Saving reloads. `setup()` reads `config` once, so a token that
       * changed only reaches the plugin by running its setup again.
       */
      .put(
        "/:name/settings",
        async ({ params, body }) => {
          const saved = await runtime.saveSettings(params.name, body.values);
          if (Result.isError(saved)) {
            if (saved.error.startsWith("no plugin named")) {
              return fail(new NotFound({ what: "plugin", id: params.name }));
            }
            return refuse(400, "UnknownPluginSetting", saved.error);
          }
          return { name: params.name, settings: redact(saved.value) } satisfies PluginSettingsView;
        },
        {
          params: t.Object({ name: t.String() }),
          body: t.Object({ values: t.Record(t.String(), t.Union([t.String(), t.Null()])) }),
        },
      )
  );
}

/**
 * The runtime answers with a plain string when it cannot do it, because it has
 * no business knowing about HTTP. This is the boundary that gives that string a
 * status code — PLAN section 10 rule 5.
 */
function toggle(outcome: Result<PluginStatus, string>, name: string) {
  if (Result.isOk(outcome)) return view(outcome.value);
  // "No such plugin" is a 404 in the shared taxonomy; anything else is a plugin
  // that exists but is in no state to be switched on, which is a conflict.
  if (outcome.error.startsWith("no plugin named")) {
    return fail(new NotFound({ what: "plugin", id: name }));
  }
  return status(409, { tag: "PluginUnavailable", message: outcome.error, retryable: false });
}
