/**
 * The database connection — and the only module that knows we are on SQLite.
 *
 * Everything above this file talks to Drizzle, never to a driver and never to
 * dialect-specific SQL (PLAN §17, rule 6). The `Database` import, the file
 * paths and the connection pragmas below are the whole of the SQLite-specific
 * surface; swapping to Postgres is a change to this file plus a regenerated
 * migration folder, not a rewrite.
 *
 * ⚠️ There are **two** SQLite files under `DATA_DIR`, by decision (PLAN §9):
 * this one, and bunqueue's. One volume still holds both, and a directory copy
 * still backs both up. The cost is that a job's row and its queue entry cannot
 * be written in one transaction — see `queue.ts` and `recoverOnStart()`.
 */
import { Database } from "bun:sqlite";
import { mkdirSync } from "node:fs";
import { dirname, isAbsolute, join, resolve } from "node:path";
import { drizzle, type BunSQLiteDatabase } from "drizzle-orm/bun-sqlite";
import { migrate } from "drizzle-orm/bun-sqlite/migrator";
import * as schema from "./schema";

export type Db = BunSQLiteDatabase<typeof schema> & { $client: Database };

/** Generated by `drizzle-kit generate`; committed, never hand-edited. */
export const MIGRATIONS_FOLDER: string = resolve(import.meta.dir, "../../drizzle");

const IN_MEMORY = ":memory:";

/** `DATA_DIR` from the environment — PLAN §12. Both databases live here. */
export function dataDir(): string {
  return process.env.DATA_DIR ?? "./data";
}

/** Our Drizzle database. */
export function appDbPath(dir: string = dataDir()): string {
  return join(dir, "casatube.db");
}

/**
 * bunqueue's own database. A **different file** from `appDbPath` — the two
 * cannot share a connection, and pretending otherwise is what would make the
 * drift silent instead of reconcilable.
 */
export function queueDbPath(dir: string = dataDir()): string {
  return join(dir, "queue.db");
}

export interface OpenDbOptions {
  /** Defaults to `appDbPath()`. `:memory:` is allowed, but see the warning. */
  path?: string;
  migrationsFolder?: string;
  /** Off only for tooling that wants a raw handle. Defaults to on. */
  applyMigrations?: boolean;
}

/**
 * Open the application database and bring it up to date.
 *
 * ⚠️ `:memory:` is accepted for convenience and is **not** good enough for the
 * tests that matter: restart recovery has to close and reopen a real file, or
 * it proves nothing (PLAN §19, and the trap list in WORKLOG).
 */
export function openDb(options: OpenDbOptions = {}): Db {
  const path = options.path ?? appDbPath();

  if (path !== IN_MEMORY) {
    const absolute = isAbsolute(path) ? path : resolve(path);
    mkdirSync(dirname(absolute), { recursive: true });
  }

  const client = new Database(path, { create: true });
  // Connection settings, not queries: WAL so a reader never blocks the claim
  // update, and a busy timeout so a concurrent writer waits instead of failing.
  client.exec("PRAGMA journal_mode = WAL;");
  client.exec("PRAGMA busy_timeout = 5000;");
  client.exec("PRAGMA foreign_keys = ON;");

  const db = drizzle(client, { schema }) as Db;

  if (options.applyMigrations !== false) {
    migrate(db, { migrationsFolder: options.migrationsFolder ?? MIGRATIONS_FOLDER });
  }

  return db;
}

export function closeDb(db: Db): void {
  db.$client.close(false);
}
